here(part, line) as (
  select 'table grants', table_name || ':' || grantee || ':' || privilege_type
  from information_schema.role_table_grants
  where table_schema = 'public' and grantee in ('anon', 'authenticated')
  union all
  select 'definer functions', p.proname || '(' || pg_get_function_identity_arguments(p.oid) || '):' ||
         coalesce(array_to_string(p.proconfig, ','), '') || ':' || md5(p.prosrc)
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prosecdef
  union all
  select 'function execute', p.proname || '(' || pg_get_function_identity_arguments(p.oid) || '):' ||
         has_function_privilege('anon', p.oid, 'execute') || ':' ||
         has_function_privilege('authenticated', p.oid, 'execute')
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
),
diff as (
  select 'only in this database' as side, part, line from (select * from here except select * from staging) x
  union all
  select 'only in staging', part, line from (select * from staging except select * from here) y
)
-- Table grants are summarised per role and privilege; functions one per row.
select side, part,
       split_part(line, ':', 2) || ' ' || split_part(line, ':', 3) as detail,
       count(*) as tables,
       string_agg(split_part(line, ':', 1), ', ' order by line) as which
from diff where part = 'table grants'
group by side, part, split_part(line, ':', 2) || ' ' || split_part(line, ':', 3)
union all
select side, part, line, null, null from diff where part <> 'table grants'
order by part, side, detail;
